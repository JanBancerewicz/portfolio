/**
 * Bakes the handful of brand marks the site actually uses into
 * `src/data/techIcons.ts`, so `simple-icons` stays a build-time dependency and
 * never ships to the browser.
 *
 * Anything without an entry here (BLE, REST, Signal Processing…) has no brand
 * mark and is rendered as a monogram chip instead — see `TechIcon`.
 *
 *   node scripts/generate-tech-icons.mjs
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

/**
 * Tag label (as written in MDX / technologies.ts) → simple-icons export.
 * Only labels the site actually uses are baked in; adding one is a line here
 * plus a re-run.
 */
const MAP = {
  Python: "siPython",
  "C++": "siCplusplus",
  TypeScript: "siTypescript",
  Kotlin: "siKotlin",
  PyTorch: "siPytorch",
  Transformers: "siHuggingface",
  "scikit-learn": "siScikitlearn",
  NumPy: "siNumpy",
  Pandas: "siPandas",
  OpenCV: "siOpencv",
  "NVIDIA Jetson": "siNvidia",
  FastAPI: "siFastapi",
  PostgreSQL: "siPostgresql",
  Docker: "siDocker",
  Linux: "siLinux",
  Git: "siGit",
  "CI/CD": "siGithubactions",
  React: "siReact",
  Vite: "siVite",
  "Tailwind CSS": "siTailwindcss",
  MDX: "siMdx",
};

const icons = {};
const missing = [];

for (const [label, key] of Object.entries(MAP)) {
  const icon = simpleIcons[key];
  if (!icon) {
    missing.push(`${label} (${key})`);
    continue;
  }
  icons[label] = { title: icon.title, hex: icon.hex, path: icon.path };
}

const body = Object.entries(icons)
  .map(
    ([label, icon]) =>
      `  ${JSON.stringify(label)}: {\n    title: ${JSON.stringify(icon.title)},\n    hex: "#${icon.hex}",\n    path: ${JSON.stringify(icon.path)},\n  },`,
  )
  .join("\n");

const file = `/* Generated by scripts/generate-tech-icons.mjs — do not edit by hand. */

export type TechIconData = {
  title: string;
  /** Brand colour, used only on hover so the row stays monochrome at rest. */
  hex: string;
  /** 24x24 SVG path. */
  path: string;
};

/** Labels without an entry here fall back to a monogram chip. */
export const techIcons: Record<string, TechIconData> = {
${body}
};
`;

writeFileSync(join(root, "src/data/techIcons.ts"), file, "utf8");

console.log(`wrote src/data/techIcons.ts (${Object.keys(icons).length} marks)`);
if (missing.length) {
  console.log(`no brand mark, will render as monogram: ${missing.join(", ")}`);
}
